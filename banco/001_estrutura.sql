-- Cria uma atividade avulsa no tópico, com o próximo número livre (tópico 4.1 -> 4.1.N).
-- Roda com as permissões de quem chama: as regras de acesso continuam valendo.
create function public.rpsq_criar_avulsa(p_trecho text, p_topico text, p_nome text, p_unidade text)
returns public.rpsq_atividades
language plpgsql set search_path = ''
as $$
declare
  v_nome_topico text;
  v_numero      integer;
  v_nova        public.rpsq_atividades;
begin
  if coalesce(public.rpsq_papel(), '') not in ('admin', 'edita') then
    raise exception 'Você não tem permissão para criar atividades.';
  end if;
  if coalesce(trim(p_nome), '') = '' or coalesce(trim(p_unidade), '') = '' then
    raise exception 'Informe o nome e a unidade da atividade.';
  end if;

  select nome_topico into v_nome_topico
    from public.rpsq_atividades
   where trecho_id = p_trecho and topico = p_topico
   limit 1;
  if not found then
    raise exception 'O tópico % não existe no trecho %.', p_topico, p_trecho;
  end if;

  -- Impede que duas pessoas peguem o mesmo número ao mesmo tempo.
  perform pg_advisory_xact_lock(hashtext('rpsq_avulsa:' || p_trecho || ':' || p_topico));

  select coalesce(max(substr(codigo, length(p_topico) + 2)::integer), 0) + 1 into v_numero
    from public.rpsq_atividades
   where trecho_id = p_trecho
     and codigo ~ ('^' || replace(p_topico, '.', '\.') || '\.[0-9]+$');

  insert into public.rpsq_atividades (trecho_id, codigo, nome, unidade, topico, nome_topico, avulsa)
  values (p_trecho, p_topico || '.' || v_numero, upper(trim(p_nome)), upper(trim(p_unidade)),
          p_topico, v_nome_topico, true)
  returning * into v_nova;
  return v_nova;
end
$$;

-- Abre a semana seguinte à mais recente (só administrador), copiando dela:
--   PROG. 1 -> EXEC. da semana nova, com as células que têm torres marcadas "a confirmar";
--   PROG. 2 -> PROG. 1; a PROG. 2 nova começa vazia;
--   encarregados acompanham as linhas e comentários acompanham as células;
--   atividades visíveis, previsto e acumulado são copiados.
-- Se ainda não existe nenhuma semana, cria a primeira vazia.
create function public.rpsq_abrir_semana(p_nova date) returns void
language plpgsql set search_path = ''
as $$
declare
  v_anterior date;
begin
  if public.rpsq_papel() is distinct from 'admin' then
    raise exception 'Só o administrador pode abrir semana.';
  end if;
  if extract(isodow from p_nova) <> 1 then
    raise exception 'A semana tem de começar numa segunda-feira; % não é.', to_char(p_nova, 'DD/MM/YYYY');
  end if;
  if exists (select 1 from public.rpsq_semanas where inicio = p_nova) then
    raise exception 'A semana de % já existe.', to_char(p_nova, 'DD/MM/YYYY');
  end if;

  v_anterior := public.rpsq_semana_atual();
  if v_anterior is not null and p_nova <> v_anterior + 7 then
    raise exception 'A semana nova tem de ser a seguinte à mais recente: %.', to_char(v_anterior + 7, 'DD/MM/YYYY');
  end if;

  insert into public.rpsq_semanas (inicio) values (p_nova);
  if v_anterior is null then
    return;
  end if;

  insert into public.rpsq_planilha (semana, canteiro_id, atividade_id, visivel)
  select p_nova, canteiro_id, atividade_id, visivel
    from public.rpsq_planilha where semana = v_anterior;

  insert into public.rpsq_controle (semana, atividade_id, previsto, acumulado)
  select p_nova, atividade_id, previsto, acumulado
    from public.rpsq_controle where semana = v_anterior;

  insert into public.rpsq_linhas (semana, canteiro_id, atividade_id, tipo, encarregado)
  select p_nova, canteiro_id, atividade_id, case tipo when 'P1' then 'E' else 'P1' end, encarregado
    from public.rpsq_linhas
   where semana = v_anterior and tipo in ('P1', 'P2') and encarregado <> '';

  insert into public.rpsq_celulas (semana, canteiro_id, atividade_id, tipo, dia, torres, comentario, a_confirmar)
  select p_nova, canteiro_id, atividade_id, case tipo when 'P1' then 'E' else 'P1' end, dia,
         torres, comentario, tipo = 'P1' and cardinality(torres) > 0
    from public.rpsq_celulas
   where semana = v_anterior and tipo in ('P1', 'P2')
     and (cardinality(torres) > 0 or comentario <> '');
end
$$;

-- Lista de usuários do RPSQ com o e-mail de login (só administrador).
-- security definer: o e-mail fica em auth.users, que o app não lê diretamente.
create function public.rpsq_listar_usuarios()
returns table (id uuid, email text, nome text, papel text, ativo boolean)
language plpgsql stable security definer set search_path = ''
as $$
#variable_conflict use_column
begin
  if public.rpsq_papel() is distinct from 'admin' then
    raise exception 'Só o administrador vê a lista de usuários.';
  end if;
  return query
    select u.user_id, a.email::text, u.nome, u.papel, u.ativo
      from public.rpsq_usuarios u
      join auth.users a on a.id = u.user_id
     order by u.nome;
end
$$;

-- Inclui ou altera um usuário do RPSQ pelo e-mail (só administrador).
-- A pessoa precisa já ter login no projeto (criado no painel, em Authentication > Users).
create function public.rpsq_gravar_usuario(p_email text, p_nome text, p_papel text, p_ativo boolean)
returns uuid
language plpgsql security definer set search_path = ''
as $$
declare
  v_id uuid;
begin
  if public.rpsq_papel() is distinct from 'admin' then
    raise exception 'Só o administrador altera usuários.';
  end if;
  select id into v_id from auth.users where lower(email) = lower(trim(p_email));
  if v_id is null then
    raise exception 'Não existe login com o e-mail % no projeto. Crie antes no painel do Supabase (Authentication > Users).', p_email;
  end if;
  if v_id = auth.uid() and (p_papel <> 'admin' or not p_ativo) then
    raise exception 'Você não pode tirar o seu próprio acesso de administrador.';
  end if;
  insert into public.rpsq_usuarios (user_id, nome, papel, ativo)
  values (v_id, trim(p_nome), p_papel, p_ativo)
  on conflict (user_id) do update
    set nome = excluded.nome, papel = excluded.papel, ativo = excluded.ativo;
  return v_id;
end
$$;

-- -------------------------------------------------------------------------------------
-- 6. Visão para a fase 2: uma linha por torre lançada, no formato da aba REGISTROS
--    do controle de produção. security_invoker: obedece às regras de acesso de quem consulta.
-- -------------------------------------------------------------------------------------

create view public.rpsq_registros with (security_invoker = true) as
select c.semana,
       c.semana + (case c.tipo when 'E' then -7 when 'P1' then 0 else 7 end) + c.dia as data,
       a.trecho_id,
       a.codigo  as atividade_codigo,
       a.nome    as atividade_nome,
       a.unidade,
       t.torre,
       case c.tipo when 'E' then 'executado' else 'programado' end as situacao,
       c.tipo,
       k.nome    as canteiro,
       coalesce(l.encarregado, '') as encarregado
  from public.rpsq_celulas c
  join public.rpsq_atividades a on a.id = c.atividade_id
  join public.rpsq_canteiros  k on k.id = c.canteiro_id
  left join public.rpsq_linhas l
         on l.semana = c.semana and l.canteiro_id = c.canteiro_id
        and l.atividade_id = c.atividade_id and l.tipo = c.tipo
  cross join lateral unnest(c.torres) as t (torre);

-- -------------------------------------------------------------------------------------
-- 7. Regras de acesso (RLS)
--    Ninguém sem papel no RPSQ lê nada. Usuário anônimo (sem login) não tem acesso algum.
-- -------------------------------------------------------------------------------------

alter table public.rpsq_usuarios   enable row level security;
alter table public.rpsq_config     enable row level security;
alter table public.rpsq_trechos    enable row level security;
alter table public.rpsq_canteiros  enable row level security;
alter table public.rpsq_torres     enable row level security;
alter table public.rpsq_atividades enable row level security;
alter table public.rpsq_semanas    enable row level security;
alter table public.rpsq_planilha   enable row level security;
alter table public.rpsq_linhas     enable row level security;
alter table public.rpsq_celulas    enable row level security;
alter table public.rpsq_controle   enable row level security;

-- Usuários: cada um lê a própria linha; o administrador lê e altera todas.
create policy rpsq_ler on public.rpsq_usuarios for select to authenticated
  using (user_id = (select auth.uid()) or (select public.rpsq_papel()) = 'admin');
create policy rpsq_admin on public.rpsq_usuarios for all to authenticated
  using ((select public.rpsq_papel()) = 'admin')
  with check ((select public.rpsq_papel()) = 'admin');

-- Configuração: todos com papel leem; só o administrador altera.
create policy rpsq_ler on public.rpsq_config for select to authenticated
  using ((select public.rpsq_papel()) is not null);
create policy rpsq_admin on public.rpsq_config for all to authenticated
  using ((select public.rpsq_papel()) = 'admin')
  with check ((select public.rpsq_papel()) = 'admin');

-- Trechos, canteiros e torres: só leitura pelo app (a carga é feita por script).
create policy rpsq_ler on public.rpsq_trechos for select to authenticated
  using ((select public.rpsq_papel()) is not null);
create policy rpsq_ler on public.rpsq_canteiros for select to authenticated
  using ((select public.rpsq_papel()) is not null);
create policy rpsq_ler on public.rpsq_torres for select to authenticated
  using ((select public.rpsq_papel()) is not null);

-- Atividades: quem edita cria avulsas; só o administrador altera o catálogo.
create policy rpsq_ler on public.rpsq_atividades for select to authenticated
  using ((select public.rpsq_papel()) is not null);
create policy rpsq_criar on public.rpsq_atividades for insert to authenticated
  with check ((select public.rpsq_papel()) = 'admin'
              or ((select public.rpsq_papel()) = 'edita' and avulsa));
create policy rpsq_alterar on public.rpsq_atividades for update to authenticated
  using ((select public.rpsq_papel()) = 'admin')
  with check ((select public.rpsq_papel()) = 'admin');
create policy rpsq_apagar on public.rpsq_atividades for delete to authenticated
  using ((select public.rpsq_papel()) = 'admin');

-- Semanas: todos leem; só o administrador abre e altera (revisão, elaborado por).
create policy rpsq_ler on public.rpsq_semanas for select to authenticated
  using ((select public.rpsq_papel()) is not null);
create policy rpsq_admin on public.rpsq_semanas for all to authenticated
  using ((select public.rpsq_papel()) = 'admin')
  with check ((select public.rpsq_papel()) = 'admin');

-- Lançamentos: todos leem; quem edita grava, e só na semana mais recente.
create policy rpsq_ler on public.rpsq_planilha for select to authenticated
  using ((select public.rpsq_papel()) is not null);
create policy rpsq_gravar on public.rpsq_planilha for all to authenticated
  using ((select public.rpsq_papel()) in ('admin', 'edita') and semana = (select public.rpsq_semana_atual()))
  with check ((select public.rpsq_papel()) in ('admin', 'edita') and semana = (select public.rpsq_semana_atual()));

create policy rpsq_ler on public.rpsq_linhas for select to authenticated
  using ((select public.rpsq_papel()) is not null);
create policy rpsq_gravar on public.rpsq_linhas for all to authenticated
  using ((select public.rpsq_papel()) in ('admin', 'edita') and semana = (select public.rpsq_semana_atual()))
  with check ((select public.rpsq_papel()) in ('admin', 'edita') and semana = (select public.rpsq_semana_atual()));

create policy rpsq_ler on public.rpsq_celulas for select to authenticated
  using ((select public.rpsq_papel()) is not null);
create policy rpsq_gravar on public.rpsq_celulas for all to authenticated
  using ((select public.rpsq_papel()) in ('admin', 'edita') and semana = (select public.rpsq_semana_atual()))
  with check ((select public.rpsq_papel()) in ('admin', 'edita') and semana = (select public.rpsq_semana_atual()));

create policy rpsq_ler on public.rpsq_controle for select to authenticated
  using ((select public.rpsq_papel()) is not null);
create policy rpsq_gravar on public.rpsq_controle for all to authenticated
  using ((select public.rpsq_papel()) in ('admin', 'edita') and semana = (select public.rpsq_semana_atual()))
  with check ((select public.rpsq_papel()) in ('admin', 'edita') and semana = (select public.rpsq_semana_atual()));

-- -------------------------------------------------------------------------------------
-- 8. Permissões de tabela e de função
--    Segunda camada de proteção, além das regras acima: o papel anônimo não recebe nada.
-- -------------------------------------------------------------------------------------

revoke all on public.rpsq_usuarios, public.rpsq_config, public.rpsq_trechos, public.rpsq_canteiros,
              public.rpsq_torres, public.rpsq_atividades, public.rpsq_semanas, public.rpsq_planilha,
              public.rpsq_linhas, public.rpsq_celulas, public.rpsq_controle, public.rpsq_registros
  from anon, authenticated;

grant select on public.rpsq_trechos, public.rpsq_canteiros, public.rpsq_torres, public.rpsq_registros
  to authenticated;
grant select, insert, update, delete on public.rpsq_usuarios, public.rpsq_config, public.rpsq_atividades,
              public.rpsq_semanas, public.rpsq_planilha, public.rpsq_linhas, public.rpsq_celulas,
              public.rpsq_controle
