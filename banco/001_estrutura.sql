-- -------------------------------------------------------------------------------------
-- 10. Conferência. O resultado aparece embaixo do editor depois de rodar.
--     Esperado: 11 tabelas com rls_ligada = true e regras >= 1, a visão rpsq_registros,
--     e anonimo_le = false em TODAS as linhas.
-- -------------------------------------------------------------------------------------

select c.relname as tabela,
       case c.relkind when 'v' then 'visão' else 'tabela' end as tipo,
       c.relrowsecurity as rls_ligada,
       (select count(*) from pg_policies p
         where p.schemaname = 'public' and p.tablename = c.relname) as regras,
       has_table_privilege('anon', c.oid, 'select') as anonimo_le
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
 where n.nspname = 'public' and c.relname like 'rpsq\_%' and c.relkind in ('r', 'v')
 order by c.relkind, c.relname;

