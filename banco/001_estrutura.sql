-- -------------------------------------------------------------------------------------
-- 1. Quem pode usar o RPSQ
-- -------------------------------------------------------------------------------------

create table public.rpsq_usuarios (
  user_id uuid primary key references auth.users (id) on delete cascade,
  nome    text not null,
  papel   text not null check (papel in ('admin', 'edita', 'consulta')),
  ativo   boolean not null default true
);

-- Papel de quem está logado: 'admin', 'edita', 'consulta', ou nulo se a pessoa não está
-- na lista do RPSQ ou está inativa. É a base de todas as regras de acesso.
-- security definer: lê rpsq_usuarios sem passar pela regra da própria tabela (evita recursão).
create function public.rpsq_papel() returns text
language sql stable security definer set search_path = ''
as $$
  select papel from public.rpsq_usuarios where user_id = auth.uid() and ativo
$$;

-- -------------------------------------------------------------------------------------
-- 2. Dados de base (carregados por script; o app só lê)
-- -------------------------------------------------------------------------------------

-- Textos do cabeçalho e do nome do arquivo Excel. Chaves usadas pelo app:
-- contratante, contratada, contrato, codigo_formulario.
create table public.rpsq_config (
  chave text primary key,
  valor text not null default ''
);

create table public.rpsq_trechos (
  id      text primary key,
  sigla   text not null,
  nome_lt text not null,
  ordem   integer not null default 0
);

create table public.rpsq_canteiros (
  id        bigint generated by default as identity primary key,
  trecho_id text not null references public.rpsq_trechos (id),
  nome      text not null,
  ordem     integer not null default 0,
  unique (trecho_id, nome)
);

-- ordem = posição da torre na linha (a do controle de produção, não a numérica).
-- vao_m = vão à frente, em metros.
create table public.rpsq_torres (
  trecho_id text not null references public.rpsq_trechos (id),
  ordem     integer not null,
  codigo    text not null check (codigo ~ '^[0-9]+/[0-9]+[A-Za-z]?$'),
  familia   text not null check (familia in ('A', 'E')),
  tipo      text not null default '',
  vao_m     numeric not null check (vao_m >= 0),
  primary key (trecho_id, ordem),
  unique (trecho_id, codigo)
);

-- Catálogo de atividades, por trecho. coluna_producao fica para a fase 2.
create table public.rpsq_atividades (
  id              bigint generated by default as identity primary key,
  trecho_id       text not null references public.rpsq_trechos (id),
  codigo          text not null,
  nome            text not null,
  unidade         text not null,
  topico          text not null,
  nome_topico     text not null default '',
  avulsa          boolean not null default false,
  ativa           boolean not null default true,
  coluna_producao integer,
  criada_por      uuid default auth.uid(),
  criada_em       timestamptz not null default now(),
  unique (trecho_id, codigo)
);

-- -------------------------------------------------------------------------------------
-- 3. Semanas e lançamentos
-- -------------------------------------------------------------------------------------

-- inicio = a segunda-feira em que a RPSQ é enviada.
create table public.rpsq_semanas (
  inicio        date primary key check (extract(isodow from inicio) = 1),
  revisao       integer not null default 0 check (revisao >= 0),
  elaborado_por text not null default '',
  criada_por    uuid default auth.uid(),
  criada_em     timestamptz not null default now(),
  alterado_por  uuid,
  alterado_em   timestamptz
);

-- Só a semana mais recente aceita lançamentos; as anteriores ficam para consulta.
create function public.rpsq_semana_atual() returns date
language sql stable set search_path = ''
as $$
  select max(inicio) from public.rpsq_semanas
$$;

-- Atividades que aparecem na planilha de cada canteiro, em cada semana.
create table public.rpsq_planilha (
  semana       date not null references public.rpsq_semanas (inicio) on delete cascade,
  canteiro_id  bigint not null references public.rpsq_canteiros (id),
  atividade_id bigint not null references public.rpsq_atividades (id),
  visivel      boolean not null default true,
  alterado_por uuid,
  alterado_em  timestamptz,
  primary key (semana, canteiro_id, atividade_id)
);

-- Encarregado de cada linha. tipo: E = executado, P1 = programação 1, P2 = programação 2.
create table public.rpsq_linhas (
  semana       date not null references public.rpsq_semanas (inicio) on delete cascade,
  canteiro_id  bigint not null references public.rpsq_canteiros (id),
  atividade_id bigint not null references public.rpsq_atividades (id),
  tipo         text not null check (tipo in ('E', 'P1', 'P2')),
  encarregado  text not null default '',
  alterado_por uuid,
  alterado_em  timestamptz,
  primary key (semana, canteiro_id, atividade_id, tipo)
);

-- Os lançamentos: uma linha por célula. dia: 0 = segunda ... 6 = domingo.
-- torres: códigos das torres; em atividade de KM, a torre onde cada vão começa.
-- a_confirmar: célula amarela, copiada da semana anterior e ainda não revisada.
create table public.rpsq_celulas (
  semana       date not null references public.rpsq_semanas (inicio) on delete cascade,
  canteiro_id  bigint not null references public.rpsq_canteiros (id),
  atividade_id bigint not null references public.rpsq_atividades (id),
  tipo         text not null check (tipo in ('E', 'P1', 'P2')),
  dia          smallint not null check (dia between 0 and 6),
  torres       text[] not null default '{}',
  comentario   text not null default '',
  a_confirmar  boolean not null default false,
  alterado_por uuid,
  alterado_em  timestamptz,
  primary key (semana, canteiro_id, atividade_id, tipo, dia)
);

-- TOTAL PREVISTO e ACUM. ATUAL, digitados por atividade do trecho.
create table public.rpsq_controle (
  semana       date not null references public.rpsq_semanas (inicio) on delete cascade,
  atividade_id bigint not null references public.rpsq_atividades (id),
  previsto     numeric,
  acumulado    numeric,
  alterado_por uuid,
  alterado_em  timestamptz,
  primary key (semana, atividade_id)
);

